const names = [...new Set(ICONS)].sort().join(",");
const css = await fetch(
  `https://fonts.googleapis.com/css2?family=Material+Symbols+Rounded:opsz,wght,FILL,GRAD@20..48,400,0..1,0&icon_names=${names}&display=block`,
  // A browser user agent, or Google serves TTF instead of woff2.
  {
    headers: {
      "user-agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 Chrome/130 Safari/537.36",
    },
  },
).then((r) => r.text());
const url = css.match(/url\((https:[^)]+)\)/)?.[1];
if (!url) throw new Error(`No font URL in:\n${css}`);
const font = Buffer.from(await fetch(url).then((r) => r.arrayBuffer()));
await writeFile(new URL("../public/fonts/material-symbols-rounded.woff2", import.meta.url), font);
console.log(`Wrote ${font.length} bytes, ${ICONS.length} icons`);
